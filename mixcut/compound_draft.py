VERSION = "compound-draft-v3"
MAX_CHILD_DEPTH = 4
ARCHIVE_DIR = "_MixCut_旧版本"


def draft_root(project: Project, output: str = "") -> Path:
    options = project.config.get("render", {}).get("jianying", {})
    configured = options.get("draft_root", "")
    if output:
        return Path(output).resolve()
    return project.asset(configured) if configured else project.path / "07_剪映草稿"


def archive_old_drafts(project: Project, *, keep=(), keep_singles: bool = False, output: str = "") -> dict:
    """Move every other MixCut draft into the archive subfolder.

    JianYing lists the newest draft first, so a clean root makes the batch that
    was just generated the first card.  Folders are moved, never deleted, and a
    folder that the client still holds open is skipped instead of being touched.
    """
    root = draft_root(project, output)
    if not root.is_dir():
        return {"archived": 0, "kept": [], "skipped_locked": [], "archive": None}
    names = {Path(item).name for item in keep if item}
    if not names:
        latest = read_json(project.state / "last_compound_draft.json", {})
        if latest.get("draft_path"):
            names.add(Path(latest["draft_path"]).name)
    if keep_singles:
        for value in read_json(project.state / "render_status.json", {}).values():
            if isinstance(value, dict) and value.get("path"):
                names.add(Path(value["path"]).name)
    archive = root / ARCHIVE_DIR / now().replace(":", "-").replace("+00:00", "Z")
    moved, locked = [], []
    for folder in sorted(root.iterdir()):
        if not folder.is_dir() or not folder.name.startswith("MixCut_") or folder.name in names:
            continue
        archive.mkdir(parents=True, exist_ok=True)
        try:
            folder.rename(archive / folder.name)
            moved.append(folder.name)
        except OSError:
            locked.append(folder.name)
    return {"archived": len(moved), "kept": sorted(names), "skipped_locked": locked,
            "archive": str(archive) if moved else None}


def flat_content(content: dict) -> dict:
    """Return the innermost timeline of a single draft.

    Current drafts are already flat (effects on segments, corners on top tracks),
    but batches generated by older versions embedded a corner wrapper.  Taking the
    inner timeline keeps those plans usable and never emits a compound inside a
    compound, which JianYing cannot resolve.
    """
    value=content
    for _ in range(MAX_CHILD_DEPTH):
        drafts=value.get("materials",{}).get("drafts") if isinstance(value,dict) else None
        if not isinstance(drafts,list) or not drafts:return value
        child=drafts[0].get("draft") if isinstance(drafts[0],dict) else None
        if not isinstance(child,dict) or int(child.get("duration",0))<=0:return value
        value=child
    raise PipelineError("子草稿嵌套层级过深，请重新生成该计划的草稿。")


def selected_plans(project, plan_ids, *, batch_id=None, all_plans=False):
    paths = scoped_paths(project,plan_ids,batch_id=batch_id,all_plans=all_plans)
    plans = []
    for path in paths:
        plan = read_json(path)
        if not plan:
            raise PipelineError("找不到组合计划：" + path.stem)
        eligible = plan.get("mode") == "folder_mix" and plan.get("render", {}).get("output_mode") == "jianying"
        if not eligible and not all_plans:
            raise PipelineError("批量复合草稿只支持文件夹模式的剪映计划：" + path.stem)
        if eligible:
            plans.append(plan)
    if not plans:
        raise PipelineError("没有可用的剪映组合计划；请先生成计划，并选择剪映草稿输出。")
    formats = {(p["render"]["width"], p["render"]["height"], p["render"]["fps"]) for p in plans}
    if len(formats) != 1:
        raise PipelineError("同一个批量草稿的所有计划必须使用相同画幅和帧率，请统一待完成计划的设置。")
    return plans


def verify_batch(path: Path, manifest: dict):
    """Check references without reopening an edited/encrypted client draft."""
    if not (path / "draft_content.json").is_file() or not (path / "draft_info.json").is_file():
        raise PipelineError("已有批量草稿不完整，请使用新的输出目录重新生成。")
    for entry in manifest["clips"]:
        for filename in ["draft_content.json", "sub_draft_config.json"]:
            if not (path / "subdraft" / entry["folder_id"] / filename).is_file():
                raise PipelineError("已有批量草稿缺少子草稿，请使用新的输出目录重新生成。")
        child = {}
        try:
            child = read_json(path / "subdraft" / entry["folder_id"] / "draft_content.json", {}) or {}
        except (OSError, ValueError):
            child = {}
        if child.get("materials", {}).get("drafts"):
            raise PipelineError("批量草稿的子草稿里还套着复合片段，剪映只能稳定加载一层复合；请重新生成本批复合草稿。")


def export_batch_draft(project: Project, plan_ids: list[str] | None = None, output: str = "", *, batch_id: str | None = None, all_plans: bool = False) -> dict:
    plans = selected_plans(project, plan_ids, batch_id=batch_id, all_plans=all_plans)
    batch = get_batch(project,batch_id) if plan_ids is None and not all_plans else None
    options = project.config.get("render", {}).get("jianying", {})
    configured_root = options.get("draft_root", "")
    root = Path(output).resolve() if output else project.asset(configured_root) if configured_root else project.path / "07_剪映草稿"
    # Rebuild from frozen plans, not client-modified/encrypted published drafts.
    sources = []
    for index, plan in enumerate(plans, 1):
        print(f"准备复合片段 {index}/{len(plans)}：{plan['id']}", flush=True)
        result = export_draft(project, plan["id"], str(project.state / "compound_sources"))
        source_path = Path(result["draft_path"])
        content = flat_content(read_json(source_path / "draft_content.json") or {})
        if not content or int(content.get("duration", 0)) <= 0:
            raise PipelineError("子草稿时长无效：" + plan["id"])
        sources.append((plan, result, content, source_path))
    fingerprint = object_hash({"version": VERSION, "children": [
        {"plan_id": plan["id"], "content": content} for plan, _, content, _ in sources]})
    safe_product = re.sub(r'[<>:"/\\|?*]', "_", project.keyword)[:48]
    name = f"MixCut_{len(plans)}条_复合_{safe_product}_{fingerprint[:8]}"
    root.mkdir(parents=True, exist_ok=True)
    target = root / name
    previous = read_json(target / "mixcut_batch_manifest.json")
    if previous and previous.get("fingerprint") == fingerprint:
        verify_batch(target, previous)
        write_json(project.state / "last_compound_draft.json", previous)
        if batch:
            write_json(project.state / "batch_compound_drafts" / (batch["batch_id"]+".json"),previous)
        return {**previous, "reused": True}
    if target.exists():
        raise PipelineError("同名批量草稿已存在且不完整，已保留；请选择其它输出目录。")
    staging = root / f".mixcut-compound-{uuid.uuid4().hex}"
    staging.mkdir()
    try:
        template = read_json(ROOT / "assets/jianying/compound_wrapper.json")
        parent = copy.deepcopy(sources[0][2])
        parent.update(id=new_id(), name=name, duration=0, tracks=[], materials={key: [] for key in parent["materials"]})
        # Native 11.1 uses this envelope for combinations; children retain their own schema.
        parent.update(version=360000, new_version="179.0.0")
        track = {"attribute": 0, "flag": 0, "id": new_id(), "is_default_name": False,
                 "name": "批量成片（全选后导出所选片段）", "segments": [], "type": "video"}
        parent["tracks"] = [track]
        entries, cursor = [], 0
        width, height = int(plans[0]["render"]["width"]), int(plans[0]["render"]["height"])
        timestamp = time.time()
        for index, (plan, result, content, source_path) in enumerate(sources, 1):
            if content.get("materials", {}).get("drafts"):
                raise PipelineError("子草稿仍包含复合片段，剪映只支持一层复合；请重新生成该计划草稿：" + plan["id"])
            child = isolated_child(content)
            duration = int(child["duration"])
            clip_name = f"{index:03d}_{safe_product}_{plan['id']}"
            child["name"] = clip_name
            folder_id = new_id()
            child_relative = Path("subdraft") / folder_id
            child_final = target / child_relative
            child_stage = staging / child_relative
            write_nested_drafts(child,child_final,child_stage)
            nested_root=child_stage/"subdraft"
            nested_files=[str(p.relative_to(staging)) for p in nested_root.rglob("*") if p.is_file()] if nested_root.exists() else []
            replacements = {"$segment": new_id(), "$video": new_id(), "$draft": new_id(),
                            "$combination": new_id(), "$name": clip_name}
            for group in template["materials"].values():
                for item in group:
                    replacements[item["id"]] = new_id()
            wrapper = replace_strings(template, replacements)
            segment = wrapper["segment"]
            segment.update(source_timerange={"start": 0, "duration": duration},
                           target_timerange={"start": cursor, "duration": duration}, volume=1.0, speed=1.0)
            video = wrapper["video"]
            video.update(duration=duration, width=width, height=height, material_name=clip_name)
            combination = wrapper["draft"]
            combination.update(draft=child, name=clip_name,
                draft_config_path=str(child_final / "sub_draft_config.json"),
                draft_cover_path=str(child_final / "draft_cover.jpg"),
                draft_file_path=str(child_final / "draft_content.json"))
            for group, material in [("videos", video), ("drafts", combination)]:
                parent["materials"].setdefault(group, []).append(material)
            for group, materials in wrapper["materials"].items():
                parent["materials"].setdefault(group, []).extend(materials)
            track["segments"].append(segment)
            write_json(child_stage / "draft_content.json", child)
            write_json(child_stage / "draft_info.json", child)
            write_json(child_stage / "sub_draft_config.json", {
                "audio_path": "", "cover_height": height, "cover_width": width, "cover_path": "draft_cover.jpg",
                "create_time": int(timestamp), "draft_json_file": "draft_content.json", "id": folder_id,
                "import_time_ms": int(timestamp * 1000), "is_from_multi_timeline": False, "is_from_sub_draft": True,
                "material_color_tag": "", "name": clip_name, "project_id": folder_id,
                "rough_cut_duration": duration, "rough_cut_start": 0, "source": "timeline", "type": "video"})
            corner = result.get("corner_overlay") or {}
            entries.append({"index": index, "plan_id": plan["id"], "name": clip_name, "folder_id": folder_id,
                "segment_id": segment["id"], "start_us": cursor, "duration_us": duration,
                "body_seconds": result["body_seconds"], "tail_seconds": result["tail_seconds"],
                "effect_count": len(result["native_effects"]), "music_count": len(result["music_playlist"]),
                "source_draft": str(source_path),"nested_draft_files":nested_files,
                "corner_overlay_enabled":bool(corner.get("enabled"))})
            cursor += duration
        parent["duration"] = cursor
        for filename in ["draft_content.json", "draft_info.json"]:
            write_json(staging / filename, parent)
        meta = read_json(sources[0][3] / "draft_meta_info.json")
        meta.update(draft_id=parent["id"], draft_name=name, draft_fold_path=str(target), draft_root_path=str(root),
            tm_duration=cursor, tm_draft_create=int(timestamp * 1_000_000), tm_draft_modified=int(timestamp * 1_000_000))
        write_json(staging / "draft_meta_info.json", meta)
        result = {"version": VERSION, "fingerprint": fingerprint, "draft_path": str(target), "count": len(entries),
            "plan_batch_id":batch["batch_id"] if batch else None, "plan_ids":[p["id"] for p in plans],
            "duration": cursor / 1_000_000, "clips": entries, "time": now(), "rendered": False,
            "corner_overlay": {"enabled": any(entry["corner_overlay_enabled"] for entry in entries),
                "scope": "inside_each_compound" if any(entry["corner_overlay_enabled"] for entry in entries) else None,
                "images_per_clip": 4},
            "client_load_verified": False, "note": "一个主时间线，每条成片是一个独立复合片段，内部已包含原视频、四张产品图、配乐、五层特效和四角产品图，可直接单独导出。请在剪映全选复合片段，右键选择‘导出所选片段’，分别输出 MP4；普通右上角导出会输出整条长视频。"}
        write_json(staging / "mixcut_batch_manifest.json", result)
        lines = ["# 批量复合草稿", "", f"本草稿包含 {len(entries)} 条独立成片，每条对应一个复合片段。", "",
            "1. 回到剪映首页，打开本文件夹名称对应的草稿（草稿目录须与剪映设置一致）。",
            "2. 点击主时间线内的复合片段，按 Ctrl+A 全选。",
            "3. 右键点击所选片段，选择‘导出所选片段’，在剪映内检查输出数量和保存位置并开始导出。",
            "4. 要分别输出 MP4，请使用上述所选片段入口；右上角普通‘导出’输出整条时间线。", "",
            "每个复合片段里已经包含一条完整成片：原声视频、四张产品图、顺序配乐、五层特效和四角产品图。",
            "五层特效挂在产品图片段上（片段级），四角产品图在最上层视频轨，因此四角图不会被特效影响。",
            "本工具负责生成草稿；客户端资源加载和 MP4 导出请以剪映实际结果为准。", "",
            "| 序号 | 计划 | 开始 / 秒 | 时长 / 秒 | 四角图 |", "| --- | --- | --- | --- | --- |"]
        lines.extend(f"| {e['index']} | {e['plan_id']} | {e['start_us']/1_000_000:g} | {e['duration_us']/1_000_000:g} | {'是' if e['corner_overlay_enabled'] else '否'} |" for e in entries)
        (staging / "批量导出说明.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
        verify_batch(staging, result)
        staging.rename(target)
        # Newest timestamps on both the meta and the folder keep this draft at the
        # top of the client's "recently modified" list right after generation.
        os.utime(target, None)
        write_json(project.state / "last_compound_draft.json", result)
        if batch:
            write_json(project.state / "batch_compound_drafts" / (batch["batch_id"]+".json"),result)
        if options.get("archive_old_drafts", False):
            tidy = archive_old_drafts(project, keep=[Path(target).name],
                keep_singles=bool(options.get("keep_single_drafts", False)), output=output)
            result["archived_old_drafts"] = tidy
            write_json(project.state / "last_compound_draft.json", result)
            if batch:
                write_json(project.state / "batch_compound_drafts" / (batch["batch_id"]+".json"),result)
            print(f"已归档其它 MixCut 草稿 {tidy['archived']} 个"
                  + (f"，{len(tidy['skipped_locked'])} 个正被剪映占用未移动" if tidy["skipped_locked"] else ""), flush=True)
        print(f"已生成批量复合草稿：{len(entries)} 条，{target}", flush=True)
        return result
    finally:
        # Only our freshly created staging folder may be removed on failure.
        if staging.exists() and staging.resolve().parent == root.resolve() and staging.name.startswith(".mixcut-compound-"):
            shutil.rmtree(staging)
